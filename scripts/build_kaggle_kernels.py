"""Generate the Kaggle notebooks and their metadata.

The notebooks are build artefacts, not hand-edited JSON. Keeping the source
here means a change to the training recipe is a normal code review rather than
an archaeology exercise in a diff full of escaped newlines.

Two kernels are produced under `kaggle/`:

  tidetrace-prepare-data   CPU, internet on. Downloads Zenodo, tiles it in a
                           streaming loop so the disk never holds the whole
                           archive expanded, pushes tiles to the HF dataset repo.

  tidetrace-train          GPU, internet on. Pulls tiles from HF, trains, pushes
                           the checkpoint back on every improvement, and can
                           resume after Kaggle kills the session.

Neither notebook contains a token. Both read `HF_TOKEN` from Kaggle Secrets, so
the credential lives in Kaggle's vault and never in a file.

Usage:
    python scripts/build_kaggle_kernels.py
    python scripts/kaggle_push.py prepare
"""
