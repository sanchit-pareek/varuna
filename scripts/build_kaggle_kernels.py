def kernel_metadata(slug: str, title: str, gpu: bool,
                    kernel_sources: list = None) -> dict:
    return {
        "id": "%s/%s" % (KAGGLE_USER, slug),
        "title": title,
        "code_file": "%s.ipynb" % slug,
        "language": "python",
        "kernel_type": "notebook",
        "is_private": True,
        "enable_gpu": gpu,
        "enable_tpu": False,
        "enable_internet": True,
        "dataset_sources": [],
        "competition_sources": [],
        # Chaining the data kernel is what lets the tile set stay on Kaggle: its
        # output mounts under /kaggle/input, so neither a credential nor a second
        # trip over the internet is needed to train on it.
        "kernel_sources": list(kernel_sources or []),
        "model_sources": [],
    }


def write(slug: str, title: str, cells: list, gpu: bool,
          kernel_sources: list = None) -> Path:
    folder = OUT / slug
    folder.mkdir(parents=True, exist_ok=True)
    (folder / ("%s.ipynb" % slug)).write_text(
        json.dumps(notebook(cells), indent=1), encoding="utf-8")
    (folder / "kernel-metadata.json").write_text(
        json.dumps(kernel_metadata(slug, title, gpu, kernel_sources), indent=2),
        encoding="utf-8")
    return folder


def main() -> int:
    # Kaggle derives the kernel slug from the title, so the title has to
    # slugify back to the id or it silently creates a second kernel.
    a = write("tidetrace-prepare-data", "TideTrace Prepare Data",
              prepare_cells(), gpu=False)
    b = write("tidetrace-train", "TideTrace Train",
              train_cells(), gpu=True,
              kernel_sources=["%s/tidetrace-prepare-data" % KAGGLE_USER])
    for folder in (a, b):
        nb = json.loads(next(folder.glob("*.ipynb")).read_text(encoding="utf-8"))
        print("%-44s %2d cells" % (str(folder.relative_to(ROOT)), len(nb["cells"])))
    print("\nPush with:  python scripts/kaggle_push.py prepare")
    print("            python scripts/kaggle_push.py train")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
